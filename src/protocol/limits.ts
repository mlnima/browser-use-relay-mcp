export const jsonStringPartsBytesWithin = (parts: Iterable<string>, maximum: number) => {
  let bytes = 2;
  for (const value of parts) {
    for (let index = 0; index < value.length && bytes <= maximum; index += 1) {
      const code = value.charCodeAt(index), next = value.charCodeAt(index + 1);
      if (code === 34 || code === 92 || [8, 9, 10, 12, 13].includes(code)) bytes += 2;
      else if (code <= 31) bytes += 6;
      else if (code <= 127) bytes += 1;
      else if (code <= 2_047) bytes += 2;
      else if (code >= 55_296 && code <= 56_319 && next >= 56_320 && next <= 57_343) { bytes += 4; index += 1; }
      else bytes += code >= 55_296 && code <= 57_343 ? 6 : 3;
    }
    if (bytes > maximum) return undefined;
  }
  return bytes <= maximum ? bytes : undefined;
};
